import { checkAdminRequest, logSupabaseError, recordAdminAudit } from "@/lib/api";
import { createSupabaseServerClient, getServerUser } from "@/lib/supabase/server";
import { resolveTeamLogo } from "@/lib/sports/team-logos";
import {
  MAX_UPLOAD_BYTES,
  REQUIRED_FIELDS,
  detectCombinedColumn,
  detectFixtureColumn,
  detectMapping,
  parseCompetition,
  parseKickoffTime,
  readSheetRows,
  validateRows,
  type FieldName,
  type ImportRow,
} from "@/lib/sports/fixture-import";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const privateHeaders = { "cache-control": "private, no-store" };

/** Columns the matches table will not accept beyond the mapped ones. */
type ExistingMatch = {
  fixture_id: string;
  match_date: string;
  kickoff_time: string;
  competition: string;
  home_team: string;
  away_team: string;
};

const XLSX_TYPES = new Set([
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  "application/vnd.ms-excel",
  "application/octet-stream",
  // Delimited text. Browsers report these inconsistently, so all the common
  // spellings are accepted; the extension check above is the real gate.
  "text/csv",
  "text/plain",
  "text/tab-separated-values",
  "application/csv",
  "",
]);

/** Trims a Postgres `time` value to HH:MM for comparison with sheet values. */
const shortTime = (value: string) => String(value ?? "").slice(0, 5);

/**
 * Excel fixture import.
 *
 * `mode=preview` (default) parses and validates the workbook and reports what
 * *would* happen. `mode=commit` re-parses the uploaded file and applies it.
 *
 * The file is sent again on commit rather than caching a parsed plan on the
 * server: the preview an admin approves must be the data that is written, and
 * re-validating guarantees the client cannot submit rows that were never
 * checked. Nothing is ever deleted — an import only inserts and updates.
 */
export async function POST(request: Request) {
  const access = await checkAdminRequest(request, "admin-fixtures-import", 20);
  if (access.response) return access.response;

  const client = await createSupabaseServerClient();
  if (!client) return Response.json({ error: "Database is not configured." }, { status: 503 });
  // See matches/route.ts: a dead session reads as signed out and its stale
  // cookies are cleared, rather than erroring on every request.
  const { user } = await getServerUser(client);
  if (!user) return Response.json({ error: "Administrator session expired." }, { status: 401 });

  // Parse the multipart body generated by the admin panel's file input.
  let form: FormData;
  try {
    form = await request.formData();
  } catch {
    return Response.json({ error: "Expected a file upload." }, { status: 400 });
  }

  const file = form.get("file");
  const mode = form.get("mode") === "commit" ? "commit" : "preview";
  // Optional JSON map of field -> header, letting the admin override detection.
  const mappingOverride = parseMappingOverride(form.get("mapping"));
  // Which sheet to read, when the workbook has several.
  const wantedSheet = typeof form.get("sheet") === "string" ? String(form.get("sheet")) : undefined;
  // Competition chosen by the admin, used when the file has no competition column.
  const competitionOverride = parseCompetition(form.get("competition"));
  // Extra columns the admin mapped manually.
  const fixtureColumn = typeof form.get("fixtureColumn") === "string" ? String(form.get("fixtureColumn")) : null;
  const combinedColumn = typeof form.get("combinedColumn") === "string" ? String(form.get("combinedColumn")) : null;

  if (!(file instanceof File)) {
    return Response.json({ error: "اختر ملفاً أولاً (No file selected)." }, { status: 400 });
  }
  if (file.size === 0) {
    return Response.json({ error: "الملف فارغ (The file is empty)." }, { status: 400 });
  }
  if (file.size > MAX_UPLOAD_BYTES) {
    return Response.json(
      { error: `حجم الملف يتجاوز ${Math.round(MAX_UPLOAD_BYTES / 1024 / 1024)} ميجابايت (File is too large).` },
      { status: 413 },
    );
  }
  // Accepted uploads: spreadsheets and delimited text. CSV is a first-class
  // format here — league schedules are often distributed as CSV, and a CSV is
  // always UTF-8 text (with or without a BOM) rather than a zip container.
  if (!/\.(xlsx|xlsm|xls|csv|tsv|txt)$/i.test(file.name)) {
    return Response.json(
      { error: "صيغة غير مدعومة. استخدم ‎.xlsx أو ‎.csv (Unsupported file type. Use .xlsx or .csv)." },
      { status: 400 },
    );
  }
  if (file.type && !XLSX_TYPES.has(file.type)) {
    return Response.json({ error: "نوع الملف غير مدعوم (Unsupported MIME type)." }, { status: 400 });
  }

  // ── Parse ────────────────────────────────────────────────────────────────
  let headers: string[];
  let raw: string[][];
  let sheetName = "";
  let sheetNames: string[] = [];
  let headerRow = 1;
  try {
    const buffer = Buffer.from(await file.arrayBuffer());
    ({ headers, raw, sheetName, sheetNames, headerRow } = await readSheetRows(buffer, wantedSheet));
  } catch {
    return Response.json(
      { error: "تعذر قراءة الملف. تأكد أنه ملف Excel أو CSV صالح (Could not read the file)." },
      { status: 400 },
    );
  }

  if (headers.length === 0 || raw.length === 0) {
    return Response.json(
      { error: "الملف لا يحتوي على صفوف بيانات (The file has no data rows).", sheetNames },
      { status: 400 },
    );
  }

  const mapping = { ...detectMapping(headers), ...mappingOverride };
  // A single "Home vs Away" column is only consulted when both team fields were
  // not mapped directly.
  const effectiveFixtureColumn = mapping.homeTeam && mapping.awayTeam ? null : fixtureColumn ?? detectFixtureColumn(headers, mapping);
  // A combined "date and time" column is consulted when either half is unmapped.
  // Note this must NOT be skipped just because one half was detected: a single
  // "Date & Time" header is claimed by the date field, and the time half still
  // has to be split out of each cell.
  const effectiveCombinedColumn = combinedColumn ?? detectCombinedColumn(headers, mapping);

  // A header literally called "Date" whose cells read "27/08/2026 22:00" is a
  // combined source, and the validator splits it per row. Reflecting that here
  // stops the kick-off from being reported as a missing column when the file
  // simply has no separate time column.
  // Verified against the data rather than assumed from the header: only claim the
  // date column supplies a time if its first populated cells actually contain
  // one. Otherwise a plain date-only file would be accepted here and then have
  // every single row rejected for a missing kick-off, which is a worse error.
  const dateColumnIndex = mapping.matchDate ? headers.indexOf(mapping.matchDate) : -1;
  const dateColumnCarriesTime =
    !mapping.kickoffTime &&
    dateColumnIndex !== -1 &&
    !effectiveCombinedColumn &&
    raw.slice(0, 10).some((row) => parseKickoffTime(row[dateColumnIndex]) !== null);

  // A file with no competition column is valid when the admin names the
  // competition for the import — an entire file is one league.
  const competitionSatisfied = Boolean(mapping.competition) || Boolean(competitionOverride);

  const missing = REQUIRED_FIELDS.filter((field) => {
    if (field === "competition") return !competitionSatisfied;
    if (field === "matchDate" || field === "kickoffTime") {
      // Satisfied by a direct column, by a dedicated combined column, or by a
      // date column that itself carries the time.
      return !mapping[field] && !effectiveCombinedColumn && !dateColumnCarriesTime;
    }
    if (field === "homeTeam" || field === "awayTeam") {
      return !mapping.homeTeam && !mapping.awayTeam && !effectiveFixtureColumn;
    }
    return !mapping[field];
  });

  if (missing.length) {
    // Return everything the UI needs to let the admin map the columns by hand,
    // instead of a bare error the admin cannot act on.
    return Response.json(
      {
        error: "لم يتم التعرف على كل الأعمدة المطلوبة تلقائياً. اختر العمود المقابل لكل حقل ثم أعد المعاينة.",
        code: "needs_mapping",
        headers,
        mapping,
        missingFields: missing,
        // Lets the UI show the competition selector immediately rather than
        // only after this failure, which the admin could not otherwise clear.
        hasCompetitionColumn: Boolean(mapping.competition),
        competitionSelected: Boolean(competitionOverride),
        sheetName,
        sheetNames,
        headerRow,
        detectedFixtureColumn: effectiveFixtureColumn,
        detectedCombinedColumn: effectiveCombinedColumn,
      },
      { status: 422 },
    );
  }

  const { rows, rejected, warnings } = validateRows(raw, headers, mapping, {
    fixtureColumn: effectiveFixtureColumn,
    combinedColumn: effectiveCombinedColumn,
    competitionOverride,
    headerRow,
  });

  // ── Match existing fixtures ──────────────────────────────────────────────
  const matchResult = await classifyRows(client, rows, rejected);
  if (matchResult.error) return matchResult.error;
  const { creates, updates, rejected: allRejected } = matchResult;

  if (mode === "preview") {
    return Response.json(
      {
        mode: "preview",
        headers,
        mapping,
        sheetName,
        sheetNames,
        headerRow,
        totalRows: raw.length,
        creates: creates.map((row) => ({ ...toPreview(row), warnings: warnings[row.row] ?? [] })),
        updates: updates.map(({ row, existing }) => ({
          ...toPreview(row),
          action: "update",
          changes: describeChanges(existing, row),
          warnings: warnings[row.row] ?? [],
        })),
        rejected: allRejected,
        summary: {
          toCreate: creates.length,
          toUpdate: updates.length,
          rejected: allRejected.length,
          warned: Object.keys(warnings).length,
        },
      },
      { headers: privateHeaders },
    );
  }

  // ── Commit ───────────────────────────────────────────────────────────────
  // No rows are written when any row is rejected: a partially applied import is
  // harder to reason about than a clean file. The admin fixes the sheet and
  // re-uploads — which is safe, because re-importing never duplicates.
  if (allRejected.length > 0) {
    return Response.json(
      {
        error: "لم يتم الاستيراد: توجد صفوف مرفوضة. صحّح الملف ثم أعد المحاولة (Import aborted: some rows were rejected).",
        rejected: allRejected,
        summary: { toCreate: creates.length, toUpdate: updates.length, rejected: allRejected.length },
      },
      { status: 422 },
    );
  }

  if (creates.length === 0 && updates.length === 0) {
    return Response.json(
      {
        mode: "commit",
        imported: 0, updated: 0, skipped: 0, rejected: 0,
        message: "لا توجد صفوف للاستيراد (Nothing to import).",
      },
      { headers: privateHeaders },
    );
  }

  let imported = 0;
  let updated = 0;
  const failures: { row: number; reason: string }[] = [];

  // ── Saved club logos ────────────────────────────────────────────────────
  // Resolved once per distinct team name so a large import does not issue one
  // query per row. A club with a stored logo always contributes it, which is
  // what makes "upload once, reuse everywhere" hold for imported fixtures too.
  const teamNames = [...new Set([
    ...creates.map((row) => row.homeTeam),
    ...creates.map((row) => row.awayTeam),
    ...updates.flatMap(({ row }) => [row.homeTeam, row.awayTeam]),
  ].filter(Boolean))];

  const logoByTeam = new Map<string, string | null>();
  for (const name of teamNames) {
    logoByTeam.set(name, await resolveTeamLogo(client, name));
  }

  // ── Updates first ────────────────────────────────────────────────────────
  for (const { row, existing } of updates) {
    // Only the fixture's own scheduling fields, plus a logo when the club has
    // one stored. `published` and every other manually maintained column are
    // left exactly as the admin set them.
    const patch: Record<string, unknown> = {
      match_date: row.matchDate,
      kickoff_time: row.kickoffTime,
      competition: row.competition,
      home_team: row.homeTeam,
      away_team: row.awayTeam,
      updated_at: new Date().toISOString(),
    };

    // A stored logo is written; an absent one is simply left out of the update.
    // This is the guarantee that an import never blanks an existing logo — the
    // key is omitted entirely rather than set to null.
    const homeLogo = logoByTeam.get(row.homeTeam);
    const awayLogo = logoByTeam.get(row.awayTeam);
    if (homeLogo) patch.home_team_logo = homeLogo;
    if (awayLogo) patch.away_team_logo = awayLogo;

    const { error } = await client
      .from("matches")
      .update(patch)
      .eq("fixture_id", existing.fixture_id);
    if (error) {
      logSupabaseError("admin/fixtures/import:update", error, { fixture_id: existing.fixture_id, row: row.row });
      failures.push({ row: row.row, reason: "تعذر تحديث المباراة (Could not update the match)." });
      continue;
    }
    updated += 1;
  }

  // ── Creates ──────────────────────────────────────────────────────────────
  for (const row of creates) {
    // The fixture ID is generated per date by the database, exactly as the
    // manual "add match" flow does, so imported and manual matches are identical.
    const { data: fixtureId, error: idError } = await client
      .rpc("generate_match_fixture_id", { target_date: row.matchDate });
    if (idError || !fixtureId) {
      logSupabaseError("admin/fixtures/import:fixture-id", idError ?? { message: "no id returned" }, { row: row.row });
      failures.push({ row: row.row, reason: "تعذر توليد معرّف المباراة (Could not generate a fixture ID)." });
      continue;
    }

    const { error } = await client.from("matches").insert({
      fixture_id: fixtureId,
      match_date: row.matchDate,
      kickoff_time: row.kickoffTime,
      competition: row.competition,
      home_team: row.homeTeam,
      away_team: row.awayTeam,
      // A spreadsheet never carries logos. A club with a saved crest inherits it
      // here; one without is simply left without a logo rather than blanked.
      home_team_logo: logoByTeam.get(row.homeTeam) ?? null,
      away_team_logo: logoByTeam.get(row.awayTeam) ?? null,
      published: true,
      created_by: user.id,
    });
    if (error) {
      logSupabaseError("admin/fixtures/import:insert", error, { row: row.row, fixture_id: fixtureId });
      failures.push({ row: row.row, reason: "تعذر إضافة المباراة (Could not create the match)." });
      continue;
    }

    // Record the key so a future import of the same sheet updates this row
    // instead of inserting a second copy.
    const { error: keyError } = await client.from("fixture_import_keys").insert({
      source_key: row.sourceKey,
      source_kind: row.sourceKind,
      fixture_id: fixtureId,
      created_by: user.id,
    });
    if (keyError && keyError.code !== "23505") {
      // The match exists; only its bookkeeping failed. Worth logging, not fatal.
      logSupabaseError("admin/fixtures/import:key", keyError, { row: row.row, fixture_id: fixtureId });
    }

    imported += 1;
  }

  await recordAdminAudit("import", "match", undefined, {
    file: file.name,
    imported,
    updated,
    rejected: allRejected.length,
    failed: failures.length,
  });

  return Response.json(
    {
      mode: "commit",
      imported,
      updated,
      skipped: 0,
      rejected: allRejected.length,
      failures,
      message: `تم الاستيراد: ${imported} جديد، ${updated} محدّث.`,
    },
    { headers: privateHeaders },
  );
}

/** Reads the optional column-mapping override from the form. */
function parseMappingOverride(value: FormDataEntryValue | null): Partial<Record<FieldName, string>> {
  if (typeof value !== "string" || !value.trim()) return {};
  try {
    const parsed = JSON.parse(value) as Record<string, unknown>;
    const allowed: FieldName[] = ["matchDate", "kickoffTime", "competition", "homeTeam", "awayTeam", "key"];
    const result: Partial<Record<FieldName, string>> = {};
    for (const field of allowed) {
      const header = parsed[field];
      if (typeof header === "string" && header.trim()) result[field] = header;
    }
    return result;
  } catch {
    return {};
  }
}

/**
 * Splits parsed rows into creates and updates by consulting the import-key
 * table and the existing matches.
 *
 * Matching order is deliberate:
 *   1. An import key recorded by a previous import (stable across edits).
 *   2. An exact match on the fixture's natural identity, so a fixture that was
 *      added *manually* is updated rather than duplicated by the first import.
 */
async function classifyRows(
  client: Awaited<ReturnType<typeof createSupabaseServerClient>> & {},
  rows: ImportRow[],
  rejected: { row: number; raw: Record<string, string>; reasons: string[] }[],
) {
  const rejectedRows = [...rejected];
  if (!client) {
    return { error: Response.json({ error: "Database is not configured." }, { status: 503 }) } as const;
  }
  if (rows.length === 0) {
    return { creates: [] as ImportRow[], updates: [] as { row: ImportRow; existing: ExistingMatch }[], rejected: rejectedRows } as const;
  }

  const keys = rows.map((row) => row.sourceKey);
  const { data: knownKeys, error: keyError } = await client
    .from("fixture_import_keys")
    .select("source_key, fixture_id")
    .in("source_key", keys);
  if (keyError) {
    logSupabaseError("admin/fixtures/import:keys", keyError, { keys: keys.length });
    return { error: Response.json({ error: "Could not read import keys. Is migration 008 applied?" }, { status: 500 }) } as const;
  }

  const keyToFixture = new Map<string, string>(
    (knownKeys ?? []).map((entry) => [String(entry.source_key), String(entry.fixture_id)]),
  );

  // Natural identity for rows without a recorded key, matched against matches.
  const dates = [...new Set(rows.map((row) => row.matchDate))];
  const { data: existingMatches, error: matchError } = await client
    .from("matches")
    .select("fixture_id, match_date, kickoff_time, competition, home_team, away_team")
    .in("match_date", dates);
  if (matchError) {
    logSupabaseError("admin/fixtures/import:matches", matchError, { dates: dates.length });
    return { error: Response.json({ error: "Could not read existing matches." }, { status: 500 }) } as const;
  }

  const byNatural = new Map<string, ExistingMatch>();
  for (const match of (existingMatches ?? []) as ExistingMatch[]) {
    const natural = `nat:${match.match_date}|${normaliseKey(match.competition)}|${normaliseKey(match.home_team)}|${normaliseKey(match.away_team)}`;
    byNatural.set(natural, match);
  }

  const creates: ImportRow[] = [];
  const updates: { row: ImportRow; existing: ExistingMatch }[] = [];
  const claimed = new Set<string>();

  for (const row of rows) {
    const fixtureId = keyToFixture.get(row.sourceKey);
    let existing: ExistingMatch | undefined;

    if (fixtureId) {
      existing = (existingMatches ?? []).find((m) => (m as ExistingMatch).fixture_id === fixtureId) as ExistingMatch | undefined;
      // A key can outlive its match if the match was deleted in the console.
      // Fall through to natural matching rather than failing the row.
    }
    if (!existing) existing = byNatural.get(row.sourceKey);

    if (existing) {
      if (claimed.has(existing.fixture_id)) {
        rejectedRows.push({
          row: row.row,
          raw: {},
          reasons: ["يشير إلى نفس المباراة الموجودة في صف آخر (Maps to the same existing match as another row)"],
        });
        continue;
      }
      claimed.add(existing.fixture_id);
      updates.push({ row, existing });
    } else {
      creates.push(row);
    }
  }

  return { creates, updates, rejected: rejectedRows } as const;
}

/** Mirrors the header-normalisation used when deriving keys. */
function normaliseKey(value: unknown): string {
  return String(value ?? "").trim().toLowerCase().replace(/[\s_\-.]/g, "");
}

function toPreview(row: ImportRow) {
  return {
    row: row.row,
    matchDate: row.matchDate,
    kickoffTime: row.kickoffTime,
    competition: row.competition,
    homeTeam: row.homeTeam,
    awayTeam: row.awayTeam,
    action: "create" as const,
    sourceKind: row.sourceKind,
  };
}

/** Human-readable list of what an update would change, for the preview. */
function describeChanges(existing: ExistingMatch, row: ImportRow): string[] {
  const changes: string[] = [];
  if (existing.match_date !== row.matchDate) changes.push(`التاريخ: ${existing.match_date} → ${row.matchDate}`);
  if (shortTime(existing.kickoff_time) !== row.kickoffTime) {
    changes.push(`الوقت: ${shortTime(existing.kickoff_time)} → ${row.kickoffTime}`);
  }
  if (existing.competition !== row.competition) changes.push(`البطولة: ${existing.competition} → ${row.competition}`);
  if (existing.home_team !== row.homeTeam) changes.push(`المضيف: ${existing.home_team} → ${row.homeTeam}`);
  if (existing.away_team !== row.awayTeam) changes.push(`الضيف: ${existing.away_team} → ${row.awayTeam}`);
  if (changes.length === 0) changes.push("لا تغييرات جدولية (no scheduling changes)");
  return changes;
}
